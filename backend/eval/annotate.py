"""Pre-fill a gold annotation file from the current segmentation.

Annotating a contract from a blank file is slow and error-prone; correcting a
draft is neither. This writes one gold entry per predicted segment, with the
anchors already quoted and the Layer 1 prediction filled in, so the owner only
merges over-splits, splits under-splits, fixes wrong ``clause_type`` values and
answers the one question the model cannot: ``high_risk``.

The draft is therefore *not* ground truth — it agrees with the segmenter by
construction, and evaluating an unedited draft yields a perfect score that
means nothing. The generated ``notes`` field says so in the file itself.

Usage (from ``backend/``)::

    venv\\Scripts\\python.exe eval\\annotate.py corpus\\my-contract.pdf
    venv\\Scripts\\python.exe eval\\annotate.py --all --force

Existing gold files are never overwritten without ``--force``: a day of
annotation is not recoverable from git, because the corpus is gitignored.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path
from typing import Any

# eval/ scripts run as `python eval\annotate.py` from backend/, so sys.path[0]
# is this directory, not the backend package root. Mirrors
# ml_training/scripts/_path.py.
_BACKEND_DIR = Path(__file__).resolve().parents[1]
if str(_BACKEND_DIR) not in sys.path:
    sys.path.insert(0, str(_BACKEND_DIR))

# Import-order pin: numpy must be fully materialised before anything can pull
# in spaCy (via classifier) alongside dspy/litellm, or predict_proba dies with
# "data type 'bool' not understood". Same reason as main.py / classifier.py.
import numpy  # noqa: E402, F401  isort: skip

from eval import (  # noqa: E402
    CORPUS_DIR,
    AnchorError,
    gold_path_for,
    load_contract,
    locate_segments,
    normalise,
    parse_gold,
    resolve_gold,
)
from segmentation import coverage_ratio, segment_text  # noqa: E402

#: How much of a clause to quote. Long enough to be unique within its
#: neighbourhood, short enough that a small edit to the draft is easy.
ANCHOR_START_CHARS = 40
ANCHOR_END_CHARS = 30

_DRAFT_NOTE = (
    "DRAFT generated by eval/annotate.py from the current segmentation — it "
    "agrees with the segmenter by construction. Merge/split clauses, correct "
    "clause_type, and set high_risk before using it as ground truth."
)


class DraftError(RuntimeError):
    """The draft could not be built (empty text, or anchors that do not resolve)."""


def build_draft_gold(
    extracted: Any,
    *,
    filename: str,
    classify: Any = None,
) -> dict[str, Any]:
    """Build the gold document for one contract from the current segmentation.

    ``extracted`` is a ``pdf_extract.ExtractedDocument``. ``classify`` is
    injected (``classifier.classify``) rather than imported so that tests, and
    anyone without the trained artifact, can draft anchors without loading
    spaCy. Every anchor is verified to resolve before the draft is returned —
    a draft that cannot be read back is a bug here, not an annotation the
    owner should discover later.
    """
    full_text: str = extracted.full_text
    if not full_text.strip():
        raise DraftError(
            "no text layer — this looks like a scanned PDF; OCR is Phase 5, so "
            "exclude it from the corpus for now"
        )

    normalised = normalise(full_text)
    # Empty-after-normalisation segments cannot exist (segment_text strips
    # them); filtering anyway keeps this list identical to the one
    # segmentation_eval scores, so clause ids line up with predicted starts.
    segments = [seg for seg in segment_text(full_text, extracted.layout_lines) if normalise(seg)]
    # Fails loudly if a predicted segment is not a substring of the normalised
    # document — the property both evaluators depend on.
    locate_segments(normalised, segments)

    clauses: list[dict[str, Any]] = []
    for position, segment in enumerate(segments, start=1):
        span = normalise(segment)
        clause_type: str | None = None
        if classify is not None:
            clause_type = classify(segment)[0]
        clauses.append(
            {
                "id": position,
                "anchor_start": span[:ANCHOR_START_CHARS],
                "anchor_end": span[-ANCHOR_END_CHARS:],
                "clause_type": clause_type,
                "high_risk": None,
                "risk_note": "",
            }
        )

    document: dict[str, Any] = {
        "file": filename,
        "annotator": "",
        "annotated_at": "",
        "notes": _DRAFT_NOTE,
        "clauses": clauses,
        "missing_protections": [],
    }

    # Round-trip the draft through the reader the evaluators use.
    gold = parse_gold(document, gold_path_for(Path(filename)))
    _, problems = resolve_gold(normalised, gold)
    if problems:
        raise DraftError(
            "generated anchors do not resolve (this is a bug in annotate.py): "
            + "; ".join(problems[:3])
        )

    return document


def write_gold(document: dict[str, Any], path: Path) -> None:
    """Write a gold file as UTF-8 JSON, readable and diffable by a human."""
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(
        json.dumps(document, indent=2, ensure_ascii=False) + "\n", encoding="utf-8"
    )


def _resolve_pdf(raw: str, corpus_dir: Path) -> Path:
    """Accept a path relative to the working directory or to the corpus."""
    candidate = Path(raw)
    if candidate.is_file():
        return candidate
    fallback = corpus_dir / candidate.name
    if fallback.is_file():
        return fallback
    raise FileNotFoundError(f"no such PDF: {raw}")


def annotate_pdf(
    pdf_path: Path, *, force: bool = False, classify: Any = None
) -> tuple[Path | None, str]:
    """Draft one gold file. Returns ``(written_path_or_None, status_line)``."""
    gold_path = gold_path_for(pdf_path)
    if gold_path.exists() and not force:
        return None, f"skipped (exists) — pass --force to overwrite {gold_path.name}"

    extracted, _ = load_contract(pdf_path)
    document = build_draft_gold(extracted, filename=pdf_path.name, classify=classify)
    write_gold(document, gold_path)

    segments = segment_text(extracted.full_text, extracted.layout_lines)
    coverage = coverage_ratio(extracted.full_text, segments)
    types = sorted(
        {str(clause["clause_type"]) for clause in document["clauses"] if clause["clause_type"]}
    )
    detail = f"{len(document['clauses'])} clauses, coverage {coverage:.3f}"
    detail += f", pages {extracted.text_pages}/{extracted.page_count}"
    if types:
        detail += f", types: {', '.join(types)}"
    return gold_path, f"wrote {gold_path.name} — {detail}"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        description="Pre-fill <slug>.gold.json from the current segmentation.",
    )
    parser.add_argument("pdfs", nargs="*", help="contract PDFs (e.g. corpus\\deal.pdf)")
    parser.add_argument(
        "--all", action="store_true", help="draft every PDF in the corpus directory"
    )
    parser.add_argument(
        "--force", action="store_true", help="overwrite existing gold files"
    )
    parser.add_argument(
        "--corpus", default=str(CORPUS_DIR), help=f"corpus directory (default: {CORPUS_DIR})"
    )
    parser.add_argument(
        "--no-classify",
        action="store_true",
        help="leave clause_type null instead of loading the Layer 1 classifier",
    )
    args = parser.parse_args(argv)

    corpus_dir = Path(args.corpus)
    targets: list[Path] = []
    if args.all:
        if not corpus_dir.is_dir():
            print(f"corpus directory not found: {corpus_dir}", file=sys.stderr)
            return 1
        targets.extend(sorted(corpus_dir.glob("*.pdf")))
    for raw in args.pdfs:
        try:
            targets.append(_resolve_pdf(raw, corpus_dir))
        except FileNotFoundError as exc:
            print(str(exc), file=sys.stderr)
            return 1

    if not targets:
        print(
            "nothing to do — pass a PDF path or --all "
            f"(corpus: {corpus_dir})",
            file=sys.stderr,
        )
        return 1

    classify = None
    if not args.no_classify:
        # Deferred: loading the artifact costs seconds and pulls in spaCy.
        import classifier

        classify = classifier.classify

    failures = 0
    for pdf_path in dict.fromkeys(targets):  # de-duplicate, keep order
        try:
            _, status = annotate_pdf(pdf_path, force=args.force, classify=classify)
        except (DraftError, AnchorError, OSError, ValueError) as exc:
            failures += 1
            print(f"{pdf_path.name}: FAILED — {exc}", file=sys.stderr)
            continue
        print(f"{pdf_path.name}: {status}")

    if failures:
        print(f"{failures} file(s) failed", file=sys.stderr)
    return 1 if failures else 0


if __name__ == "__main__":
    raise SystemExit(main())
